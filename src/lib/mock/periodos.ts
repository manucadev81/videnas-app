function construirEntregue(entrada: EntradaEntregue): PeriodoObrigacao {
  const modulo = buscarModulo(entrada.moduloId);

  const loteId = `lote-${entrada.id.slice(4)}-01`;
  const arquivoId = `arq-${entrada.id.slice(4)}-v1`;
  const validacaoId = `val-${entrada.id.slice(4)}-001`;
  const protocoloId = `prot-${entrada.id.slice(4)}`;

  const arquivo: ArquivoGerado = {
    id: arquivoId,
    periodoId: entrada.id,
    versao: 1,
    nomeArquivo: entrada.nomeArquivo,
    formato: "xml",
    hashSha256: gerarHashDeterministico(arquivoId),
    algoritmoHash: "SHA-256",
    tamanhoBytes: entrada.tamanhoBytes,
    tamanhoLegivel: formatarTamanhoArquivo(entrada.tamanhoBytes),
    schema: modulo.schema,
    versaoSchema: modulo.versaoSchema,
    quantidadeRegistros: entrada.quantidadeRegistros,
    geradoEm: entrada.geradoEm,
    geradoPorUsuarioId: entrada.geradoPorUsuarioId,
    situacao: "corrente",
    previewConteudo: `<${modulo.schema} versao="${modulo.versaoSchema}">\n  <Cabecalho competencia="${entrada.competencia}" registros="${entrada.quantidadeRegistros}" />\n  <!-- ${entrada.quantidadeRegistros} registros processados -->\n</${modulo.schema}>`,
    urlDownload: "#mock-download",
  };
  arquivos.push(arquivo);

  const itens = entrada.itensAviso ?? [];
  const validacao: ValidacaoResultado = {
    id: validacaoId,
    periodoId: entrada.id,
    arquivoId,
    schema: modulo.schema,
    versaoSchema: modulo.versaoSchema,
    executadaEm: entrada.geradoEm,
    executadaPorUsuarioId: "usr-clarice",
    duracaoMs: 1620 + entrada.quantidadeRegistros,
    totalErros: 0,
    totalAvisos: entrada.totalAvisos ?? itens.length,
    resultado: "aprovado",
    itens,
    regrasDeterministicas: [
      { regra: "Aderência ao schema oficial", aprovada: true },
      { regra: "Unicidade de identificadores", aprovada: true },
    ],
  };
  validacoes.push(validacao);

  const protocolo: ProtocoloBCB = {
    id: protocoloId,
    periodoId: entrada.id,
    numeroProtocolo: entrada.numeroProtocolo,
    dataHoraEnvio: entrada.dataHoraEnvio,
    canalEnvio: entrada.canalEnvio,
    registradoPorUsuarioId: entrada.registradoPorUsuarioId,
    reciboHash: gerarHashDeterministico(`recibo-${protocoloId}`),
    situacaoRetorno: entrada.situacaoRetorno ?? "aceito",
    codigoRetorno: "RET-0000",
    mensagemRetorno: "Documento processado com sucesso.",
    dataRetorno: entrada.dataHoraEnvio,
    observacao: null,
  };
  protocolos.push(protocolo);

  return {
    id: entrada.id,
    instituicaoId: entrada.instituicaoId,
    moduloId: entrada.moduloId,
    competencia: entrada.competencia,
    competenciaRotulo: entrada.competenciaRotulo,
    estado: "entregue",
    prazoEntrega: entrada.prazoEntrega,
    dataAbertura: entrada.dataAbertura,
    lotes: [
      {
        id: loteId,
        nomeArquivo: entrada.loteNomeArquivo,
        tamanhoBytes: entrada.loteTamanhoBytes,
        recebidoEm: entrada.loteRecebidoEm,
        recebidoPorUsuarioId: entrada.loteRecebidoPorUsuarioId,
        canal: "upload",
        linhasRecebidas: entrada.linhasRecebidas,
        linhasResolvidas: entrada.linhasResolvidas,
        linhasComPendencia: entrada.linhasComPendencia,
        situacao: "processado",
      },
    ],
    arquivoCorrenteId: arquivoId,
    arquivoIds: [arquivoId],
    validacaoId,
    protocoloId,
    excecaoIds: [],
    totaisResumo: entrada.totaisResumo,
    geradoPorUsuarioId: entrada.geradoPorUsuarioId,
    geradoEm: entrada.geradoEm,
    liberadoPorUsuarioId: entrada.liberadoPorUsuarioId,
    liberadoEm: entrada.liberadoEm,
    aprovadoPorUsuarioId: entrada.aprovadoPorUsuarioId,
    aprovadoEm: entrada.aprovadoEm,
    entregueEm: entrada.entregueEm,
    contadorStatus: entrada.contadorStatus ?? "nao_aplicavel",
    contadorUsuarioId: entrada.contadorUsuarioId ?? null,
    contadorConfirmadoEm: entrada.contadorConfirmadoEm ?? null,
  };
}

