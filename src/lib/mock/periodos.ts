function diferencaEmDias(dataIsoA: string, dataIsoB: string): number {
  const umDiaEmMs = 24 * 60 * 60 * 1000;
  const dataA = Date.UTC(
    Number(dataIsoA.slice(0, 4)),
    Number(dataIsoA.slice(5, 7)) - 1,
    Number(dataIsoA.slice(8, 10))
  );
  const dataB = Date.UTC(
    Number(dataIsoB.slice(0, 4)),
    Number(dataIsoB.slice(5, 7)) - 1,
    Number(dataIsoB.slice(8, 10))
  );
  return Math.round((dataA - dataB) / umDiaEmMs);
}

const ORDEM_ETAPAS: EtapaId[] = ["ingestao", "geracao", "contador", "validacao", "auditoria", "entrega"];

function calcularEtapaAtual(periodo: PeriodoObrigacao, etapasModulo: EtapaId[]): EtapaId {
  switch (periodo.estado) {
    case "aguardando_dados":
      return "ingestao";
    case "dados_ingeridos":
      return "geracao";
    case "gerado":
      return etapasModulo.includes("contador") ? "contador" : "validacao";
    case "aguardando_contador":
      return "contador";
    case "em_validacao":
    case "validado":
    case "com_excecoes":
      return "validacao";
    case "liberado":
      return "auditoria";
    case "aprovado":
      return "entrega";
    case "entregue":
      return "entrega";
    case "retorno_com_erro":
      return "entrega";
    default:
      return "ingestao";
  }
}

export function calcularPeriodoDerivado(
  periodo: PeriodoObrigacao,
  hojeIso: string = HOJE_ISO
): PeriodoDerivado {
  const modulo = buscarModulo(periodo.moduloId);
  const etapaAtual = calcularEtapaAtual(periodo, modulo.etapas);
  const indiceEtapa = ORDEM_ETAPAS.indexOf(etapaAtual);
  const indiceEtapaFiltrado = modulo.etapas.indexOf(etapaAtual);
  const progressoBase =
    indiceEtapaFiltrado >= 0 ? (indiceEtapaFiltrado / modulo.etapas.length) * 100 : 0;

  const diasParaPrazo = diferencaEmDias(periodo.prazoEntrega, hojeIso);
  const atrasado = diasParaPrazo < 0 && periodo.estado !== "entregue";
  const diasDeAtraso = atrasado ? Math.abs(diasParaPrazo) : 0;

  const progressoPercentual =
    periodo.estado === "entregue"
      ? 100
      : Math.min(95, Math.max(5, Math.round(progressoBase + (indiceEtapa >= 0 ? 5 : 0))));

  return {
    ...periodo,
    atrasado,
    diasDeAtraso,
    diasParaPrazo,
    etapaAtual,
    progressoPercentual,
  };
}
